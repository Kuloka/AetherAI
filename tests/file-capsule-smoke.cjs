'use strict';
const { app, BrowserWindow } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const { pathToFileURL } = require('node:url');
const out = path.join(root, 'artifacts', 'file-capsule');
fs.mkdirSync(out, { recursive: true });
app.setPath('userData', path.join(out, 'profile'));
app.disableHardwareAcceleration();
app.whenReady().then(async () => {
  let win;
  try {
    win = new BrowserWindow({ width: 800, height: 650, frame: false, show: false, webPreferences: { offscreen: true, contextIsolation: true, nodeIntegration: false } });
    const js = code => win.webContents.executeJavaScript(code);
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const fixturePath=path.join(out,'fixture.html');
    fs.writeFileSync(fixturePath,'<!doctype html><html><head><meta charset="utf-8"><base href="'+pathToFileURL(root+path.sep).href+'"></head><body><main id="fixture"></main></body></html>');
    await win.loadFile(fixturePath);
    for (const file of ['styles.css', 'glass.css', 'file-capsule.css']) {
      await js(`{const style=document.createElement('style');style.textContent=${JSON.stringify(fs.readFileSync(path.join(root, file), 'utf8'))};document.head.append(style);}`);
    }
    await js(fs.readFileSync(path.join(root, 'code-presentation.js'), 'utf8'));
    await js(fs.readFileSync(path.join(root, 'file-capsule.js'), 'utf8'));
    await js("document.body.style.cssText='display:block;padding:20px;margin:0;overflow:auto';document.getElementById('fixture').style.cssText='width:100%;max-width:680px';window.original=Array.from({length:100},(_,i)=>'const line'+i+' = '+i+';').join('\\n');window.changed=original.replace('const line3 = 3;','const line3 = 333;');window.capsule=AetherAIFileCapsule.create({path:'src/',file:'index.html',label:'HTML',code:changed},{before:original,baselineKnown:true,writing:true});document.getElementById('fixture').append(capsule)");
    assert.equal(await js('capsule.open'), false);
    assert.equal(await js("capsule.querySelector('.file-capsule-name').textContent"),'src/index.html');
    assert.equal(await js("getComputedStyle(capsule).borderRadius"),'22px');
    assert.ok(await js("capsule.getBoundingClientRect().width < 400"),'closed header is compact');
    assert.equal(await js("getComputedStyle(capsule.querySelector('.file-capsule-code')).display"), 'none');
    assert.equal(await js("capsule.querySelector('.file-capsule-code').getBoundingClientRect().height"), 0);
    const summary = await js("(()=>{const r=capsule.querySelector('summary').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()");
    win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...summary});
    win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...summary});
    await wait(300);
    assert.equal(await js('capsule.open'), true, 'native mouse opens disclosure');
    assert.equal(await js("getComputedStyle(capsule.querySelector('.file-capsule-arrow')).transform"), 'matrix(0, 1, -1, 0, 0, 0)');
    assert.equal(await js("capsule.querySelectorAll('.file-capsule-add').length"), 1);
    assert.equal(await js("capsule.querySelectorAll('.file-capsule-remove').length"), 1);
    assert.equal(await js("capsule.querySelectorAll('.file-capsule-context').length"), 99);
    await js("capsule.querySelector('summary').focus()");
    win.webContents.focus();
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'Return'});
    win.webContents.sendInputEvent({type:'char',keyCode:'\r'});
    win.webContents.sendInputEvent({type:'keyUp',keyCode:'Return'});
    await wait(80);
    assert.equal(await js('capsule.open'), false, 'native keyboard closes disclosure');
    win.webContents.sendInputEvent({type:'keyDown',keyCode:'Return'});
    win.webContents.sendInputEvent({type:'char',keyCode:'\r'});
    win.webContents.sendInputEvent({type:'keyUp',keyCode:'Return'});
    await wait(300);
    assert.equal(await js('capsule.open'), true);
    await js("window.firstRow=capsule.querySelector('.file-capsule-line');capsule.querySelector('.file-capsule-code').scrollTop=90;AetherAIFileCapsule.update(capsule,{path:'src/',file:'index.html',label:'HTML',code:changed+'\\nlast line'},{before:original,baselineKnown:true,writing:true})");
    assert.equal(await js('capsule.open'), true);
    assert.equal(await js("capsule.querySelector('.file-capsule-line')===firstRow"), true);
    assert.equal(await js("capsule.querySelector('.file-capsule-code').scrollTop"), 90, 'manual reading position stays fixed');
    await js("window.unknown=AetherAIFileCapsule.create({file:'unknown.js',code:'<img src=x onerror=alert(1)>\\nnext'},{writing:true});document.getElementById('fixture').append(unknown);unknown.open=true");
    assert.equal(await js("unknown.querySelectorAll('.file-capsule-add,.file-capsule-remove').length"), 0);
    assert.equal(await js("unknown.querySelector('.file-capsule-code').querySelectorAll('img').length"), 0);
    assert.equal(await js("unknown.querySelector('.file-capsule-source').textContent"), '<img src=x onerror=alert(1)>');
    await js("window.groupFiles=[{path:'src/',file:'first.js',code:'new',beforeContent:'old',baselineKnown:true,complete:true},{file:'second.js',code:'one\\ntwo',beforeContent:'',baselineKnown:true}];window.group=AetherAIFileCapsule.createGroup(groupFiles,{phase:'writing',labels:{groupFiles:'files',groupChanges:'Changes',partial:'partial',writing:'Writing',checking:'Checking',done:'Done'}});document.getElementById('fixture').append(group)");
    assert.equal(await js('group.open'),false,'group starts compact');
    assert.equal(await js("group.querySelector('.file-capsule-group-name').textContent"),'2 files');
    assert.equal(await js("group.querySelector('.file-capsule-group-counts').textContent"),'+3 / -1');
    await js("group.open=true;window.groupFirst=AetherAIFileCapsule.getCapsules(group).get('src/first.js');groupFirst.open=true;groupFirst.retainedMarker=true;AetherAIFileCapsule.updateGroup(group,[{...groupFiles[0],code:'new\\nlast'},groupFiles[1]],{phase:'checking',labels:{checking:'Checking',done:'Done'}})");
    assert.equal(await js('group.open&&groupFirst.open'),true,'both disclosure levels remain open');
    assert.equal(await js("AetherAIFileCapsule.getCapsules(group).get('src/first.js')===groupFirst"),true,'file identity preserved');
    assert.equal(await js("groupFirst.dataset.phase"),'checking');
    assert.equal(await js("group.dataset.phase"),'checking');
    assert.equal(await js("group.querySelector('.file-capsule-group-state').textContent"),'Checking');
    assert.equal(await js("groupFirst.querySelector('.file-capsule-state').textContent"),'Checking');
    assert.equal(await js("groupFirst.currentFile.code"),'new\nlast');
    await js("AetherAIFileCapsule.updateGroup(group,[groupFiles[0],{file:'unknown.js',code:'partial'}],{phase:'done',labels:{partial:'partial',done:'Done'}})");
    assert.equal(await js("group.querySelector('.file-capsule-group-counts').textContent"),'+1 / -1 \u00b7 partial','unknown baseline does not claim complete totals');
    assert.equal(await js("groupFirst.dataset.phase"),'done');
    assert.equal(await js("group.dataset.phase"),'done');
    assert.equal(await js("group.querySelector('.file-capsule-group-state').textContent"),'Done');
    assert.equal(await js("AetherAIFileCapsule.getCapsules(group).has('second.js')"),false,'removed files leave keyed map');
    await js("AetherAIFileCapsule.updateGroup(group,[{file:'unknown.js',code:'partial'},{file:'stopped.js',code:'unfinished',beforeContent:'old\\ntail',baselineKnown:true,unsaved:true}],{})");
    assert.equal(await js("group.querySelector('.file-capsule-group-counts').textContent"),'','unknown total is omitted');
    assert.equal(await js("group.dataset.phase"),'','unsaved files must not claim Done');
    assert.equal(await js("group.querySelectorAll('.file-capsule-add,.file-capsule-remove').length"),0,'stopped incomplete old file is neutral');
    await js("AetherAIFileCapsule.updateGroup(group,[groupFiles[0]],{phase:'checking',labels:{checking:'Checking'}})");
    await js("AetherAIFileCapsule.update(unknown,{file:'stopped.js',code:'partial'},{phase:'stopped',labels:{done:'Done',edited:'Stopped'}})");
    assert.equal(await js("unknown.querySelector('.file-capsule-state').textContent"),'Stopped');
    await js("AetherAIFileCapsule.update(unknown,{file:'unsaved.js',code:'partial'},{phase:'unsaved',labels:{done:'Done',edited:'Not saved'}})");
    assert.equal(await js("unknown.querySelector('.file-capsule-state').textContent"),'Not saved');
    await js("AetherAIFileCapsule.update(unknown,{file:'legacy.js',code:'partial'},{labels:{done:'Done',edited:'Legacy edited'}})");
    assert.equal(await js("unknown.querySelector('.file-capsule-state').textContent"),'Legacy edited');
    await js("AetherAIFileCapsule.update(unknown,{file:'script.py',label:'Python',code:'partial'},{writing:true})");
    assert.equal(await js("unknown.querySelector('.file-capsule-indicator').getAttribute('aria-label')"),'Python','language updates on the same capsule');
    assert.equal(await js("unknown.querySelector('.file-capsule-indicator img').getAttribute('src')"),'resources/language-icons/python.svg');
    await js("AetherAIFileCapsule.update(unknown,{file:'unknown.bin',label:'CODE',code:'partial'}, {})");
    assert.equal(await js("unknown.querySelector('.file-capsule-indicator').title"),'File');
    assert.equal(await js("unknown.querySelector('.file-capsule-indicator svg')!==null"),true,'unknown file uses thin file icon');
    for (const theme of ['dark', 'light']) {
      await js(`document.body.className='theme-${theme}'`);
      await wait(100);
      assert.equal(await js("capsule.querySelector('.file-capsule-indicator').title"),'HTML');
      assert.equal(await js("capsule.querySelector('.file-capsule-indicator img').complete&&capsule.querySelector('.file-capsule-indicator img').naturalWidth>0"),true,'existing language SVG loads in '+theme+' theme');
      assert.equal(await js("getComputedStyle(capsule.querySelector('.file-capsule-indicator img')).width"),'14px');
      const colors = await js("({add:getComputedStyle(capsule.querySelector('.file-capsule-add')).backgroundColor,remove:getComputedStyle(capsule.querySelector('.file-capsule-remove')).backgroundColor,context:getComputedStyle(capsule.querySelector('.file-capsule-context')).backgroundColor})");
      assert.notEqual(colors.add, colors.remove);
      assert.notEqual(colors.context, colors.add);
      win.webContents.invalidate(); await wait(100);
      fs.writeFileSync(path.join(out, theme+'.png'), (await win.webContents.capturePage()).toPNG());
    }
    win.setSize(360, 650);
    await js("AetherAIFileCapsule.update(capsule,{file:'a-very-long-filename-that-must-never-push-counts-outside-the-header.js',code:changed},{before:original,baselineKnown:true,writing:true})");
    await wait(150);
    assert.ok(await js("document.documentElement.scrollWidth<=innerWidth"), 'narrow viewport has no page overflow');
    assert.ok(await js("(()=>{const header=capsule.querySelector('summary').getBoundingClientRect();return [...capsule.querySelector('summary').children].every(el=>el.getBoundingClientRect().right<=header.right+1)})()"), 'header fits narrow viewport');
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Emulation.setEmulatedMedia',{features:[{name:'prefers-reduced-motion',value:'reduce'}]});
    assert.equal(await js("matchMedia('(prefers-reduced-motion: reduce)').matches"),true);
    assert.equal(await js("getComputedStyle(capsule.querySelector('.file-capsule-indicator')).animationName"), 'none');
    assert.equal(await js("getComputedStyle(group.querySelector('.file-capsule-indicator')).animationName"), 'none', 'checking respects reduced motion');
    console.log('File capsule native smoke passed: mouse + keyboard, stable DOM/scroll, real diff, safe unknown baseline, both themes, narrow width.');
    win.destroy(); app.exit(0);
  } catch(error) { console.error(error); if(win&&!win.isDestroyed())win.destroy(); app.exit(1); }
});
